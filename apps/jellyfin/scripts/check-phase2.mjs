import assert from 'node:assert/strict'
import { loadSettings, saveSettings, defaultSettings } from '../src/lib/settings.ts'
import { activeSegment, upNextThreshold } from '../src/lib/playbackTimeline.ts'
import { authenticate, createPlaybackSession, getEpisodes, getItem, getMediaSegments, getNextEpisode, getNextUp, getTrickplayImage, trickplayThumbnail } from '../src/lib/jellyfin.ts'

const store = new Map()
globalThis.localStorage = { getItem: (key) => store.get(key) ?? null, setItem: (key, value) => store.set(key, value), removeItem: (key) => store.delete(key) }
globalThis.window = new EventTarget()
globalThis.document = { createElement: () => ({ canPlayType: (mime) => /avc1|mp4a\.40\.2/.test(mime) ? 'probably' : '' }) }
assert.deepEqual(loadSettings(), defaultSettings)
saveSettings({ ...defaultSettings, speed: 1.5, subtitleDelay: 0.75, autoSkip: true })
assert.equal(loadSettings().speed, 1.5)
assert.equal(loadSettings().subtitleDelay, 0.75)
store.set('valvefin.player.settings', '{bad')
assert.deepEqual(loadSettings(), defaultSettings)
saveSettings({ ...defaultSettings, subtitleColor: '<invalid>', speed: 99 })
assert.equal(loadSettings().subtitleColor, '#ffffff')
assert.equal(loadSettings().speed, 2)
console.log('PASS settings defaults, persistence, malformed data and bounds')
const segments = [{ Id: 'intro', Type: 'Intro', StartTicks: 10000000, EndTicks: 50000000 }, { Id: 'outro', Type: 'Outro', StartTicks: 200000000, EndTicks: 650000000 }]
assert.equal(activeSegment(segments, 1).Type, 'Intro')
assert.equal(activeSegment(segments, 5), null)
assert.equal(activeSegment([], 2), null)
assert.equal(upNextThreshold(segments, 65), 20)
assert.equal(upNextThreshold([], 65), 35)
assert.equal(upNextThreshold([], 20), 0)
console.log('PASS segment boundaries, absent segments, earlier Outro / 30-second threshold')
const session = await authenticate({ serverUrl: process.env.JELLYFIN_URL || 'http://127.0.0.1:8096', username: 'devin', password: 'devin' })
const response = await fetch(`${session.serverUrl}/Users/${session.userId}/Items?Recursive=true&IncludeItemTypes=Series`, { headers: { Authorization: `MediaBrowser Client="ValveFin", Device="Test", DeviceId="${session.deviceId}", Version="1", Token="${session.accessToken}"` } })
assert.equal(response.status, 200)
const series = (await response.json()).Items.find((i) => i.Name === 'Valve Test Show')
assert.ok(series)
const episodes = await getEpisodes(session, series.Id)
assert.equal(episodes.length, 6)
assert.equal((await getNextEpisode(session, episodes[2])).Id, episodes[3].Id)
assert.equal(await getNextEpisode(session, episodes.at(-1)), null)
assert.equal(await getNextEpisode(session, series), null)
assert.ok(await getNextUp(session, series.Id))
console.log('PASS live Next Up, cross-season queue, final episode and non-episode no-op')
const fresh = await getItem(session, episodes[0].Id)
const playback = await createPlaybackSession(session, fresh, { startPositionTicks: 0 })
assert.equal(playback.startPositionTicks, 0)
const limited = await createPlaybackSession(session, fresh, { maxBitrate: 100000, maxHeight: 720 })
assert.equal(limited.playMethod, 'Transcode')
assert.equal(new URL(limited.streamUrl).searchParams.get('MaxHeight'), '720')
assert.ok(limited.info.transcodeReasons.includes('Quality limit'))
assert.ok(limited.info.videoCodec)
console.log('PASS live start-over override, low bitrate forces transcode, resolution cap and playback info')
const thumbnail = trickplayThumbnail(session, fresh, playback.mediaSourceId, 20)
assert.ok(thumbnail, 'Generate trickplay on the test library first')
const jpeg = await getTrickplayImage(session, thumbnail.url)
assert.match(jpeg.type, /image\/jpeg/)
assert.equal(trickplayThumbnail(session, { ...fresh, Trickplay: undefined }, playback.mediaSourceId, 20), null)
assert.ok(trickplayThumbnail(session, fresh, playback.mediaSourceId, 9999))
console.log('PASS live trickplay JPEG, absent manifest no-op, seek past last thumbnail clamps')
assert.ok(Array.isArray(await getMediaSegments(session, fresh.Id)))
const realFetch = globalThis.fetch
globalThis.fetch = async () => Response.json({ Items: [segments[0], { ...segments[0], Type: 'Unknown' }, { ...segments[0], EndTicks: 0 }] })
assert.equal((await getMediaSegments(session, fresh.Id)).length, 1)
globalThis.fetch = async () => new Response('Unavailable', { status: 503 })
await assert.rejects(() => getMediaSegments(session, fresh.Id))
await assert.rejects(() => getTrickplayImage(session, thumbnail.url))
let unauthorized = false
window.addEventListener('jellyfin:unauthorized', () => { unauthorized = true }, { once: true })
globalThis.fetch = async () => new Response('Expired', { status: 401 })
await assert.rejects(() => getTrickplayImage(session, thumbnail.url))
assert.equal(unauthorized, true)
globalThis.fetch = realFetch
console.log('PASS media segments live API, mocked filtering, segment/image errors and image session expiry')
